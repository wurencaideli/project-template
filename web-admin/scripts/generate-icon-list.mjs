import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const svgDir = path.join(__dirname, '../public/icons/svgs');
const imgDir = path.join(__dirname, '../public/icons/imgs');
const outputFile = path.join(__dirname, '../src/generated/icon-list.ts');

/** 递归读取目录下所有文件，返回相对路径（兼容子目录，名称保持 svg:sys/test.svg 形式） */
function readFiles(dir, filter) {
    if (!fs.existsSync(dir)) return [];
    return fs
        .readdirSync(dir, { recursive: true })
        .map((f) => f.toString())
        .filter((f) => fs.statSync(path.join(dir, f)).isFile() && filter(f));
}

const svgIcons = readFiles(svgDir, (f) => f.endsWith('.svg')).map((f) => ({
    type: 'svg',
    name: 'svg:' + f,
}));
const imgIcons = readFiles(imgDir, () => true).map((f) => ({
    type: 'img',
    name: 'img:' + f,
}));
const icons = [...svgIcons, ...imgIcons].sort((a, b) => a.name.localeCompare(b.name));

const content = `// Auto-generated by scripts/generate-icon-list.mjs — do not edit manually
export const iconList = ${JSON.stringify(icons, null, 4).replace(/"/g, "'")};
`;

fs.writeFileSync(outputFile, content, 'utf8');
console.log(`✅ Generated icon list: ${icons.length} icons → ${outputFile}`);
