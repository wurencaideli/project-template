import { execSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const outputFile = path.join(__dirname, '../src/generated/git-info.ts');

function run(cmd) {
    try {
        return execSync(cmd, { encoding: 'utf8', cwd: path.join(__dirname, '..') }).trim();
    } catch {
        return '';
    }
}

const gitInfo = {
    branch: run('git rev-parse --abbrev-ref HEAD'),
    commitId: run('git rev-parse --short HEAD'),
    fullCommitId: run('git rev-parse HEAD'),
    message: run('git log -1 --pretty=%B'),
    author: run('git log -1 --pretty=%an'),
    date: run('git log -1 --pretty=%ci'),
};

const content = `// Auto-generated by scripts/generate-git-info.js — do not edit manually
export const GIT_INFO = ${JSON.stringify(gitInfo, null, 4)} as const;
`;

fs.writeFileSync(outputFile, content, 'utf8');
console.log(`✅ Generated git info: ${gitInfo.branch}@${gitInfo.commitId} → ${outputFile}`);
