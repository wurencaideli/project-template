import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const iconDir = path.join(__dirname, '../src/assets/icon-images');
const outputFile = path.join(__dirname, '../src/generated/icon-list.ts');

const iconSrcPath = 'assets/icon-images/';
const files = fs.readdirSync(iconDir);
const icons = files
    .filter((f) => f.endsWith('.svg'))
    .map((f) => ({
        name: path.basename(f, '.svg'),
        srcPath: iconSrcPath,
        fileName: f,
    }))
    .sort((a, b) => a.name.localeCompare(b.name));

const content = `// Auto-generated by scripts/generate-icon-list.js — do not edit manually
export interface IconEntry {
    /** 图标名称（不含扩展名），作为 svg-icon 组件的 name 输入 */
    name: string;
    /** 图标所在目录路径，作为 svg-icon 组件的 svgSrcPath 输入 */
    srcPath: string;
    /** 完整文件名 */
    fileName: string;
}

export const ICON_LIST: IconEntry[] = ${JSON.stringify(icons, null, 4).replace(/"/g, "'")};

export const ICON_NAMES = [
${icons.map((i) => `    '${i.name}',`).join('\n')}
] as const;

export type IconName = (typeof ICON_NAMES)[number];
`;

fs.writeFileSync(outputFile, content, 'utf8');
console.log(`✅ Generated icon list: ${icons.length} icons → ${outputFile}`);
